package exposer

import (
	"strings"
)

const (
	maxDiagnoseSummaryLines = 5
	maxDiagnoseSummaryLen   = 1024
)

// diagnoseSummaryPrefixes are the prefixes of the DiagnoseExpose lines that
// point at the cause of an expose that never became ready. The lines are
// generated by kube.DiagnosePod, kube.DiagnosePVC, csi.DiagnoseVS and the
// exposers' DiagnoseExpose methods.
var diagnoseSummaryPrefixes = []string{
	"Pod condition PodScheduled, status False",
	"Pod event reason ",
	"PVC event reason ",
	"VS event reason ",
	"node-agent is not running",
}

// diagnoseErrorPrefix is the prefix of the DiagnoseExpose lines reporting a
// failure to get an object, e.g. an intermediate object that was never created.
// They are reported after the lines matching diagnoseSummaryPrefixes.
const diagnoseErrorPrefix = "error "

// SummarizeDiagnose picks the lines of a DiagnoseExpose result that explain
// why an expose did not complete (warning events, unschedulable pod, VS/VSC
// errors, node-agent not running, missing intermediate objects), so that they
// can be put into the message of the DU/DD/PVB/PVR. The result is capped in
// lines and length; the full diagnose output should still be logged.
func SummarizeDiagnose(diag string) string {
	causes := []string{}
	errs := []string{}
	seen := map[string]bool{}

	for line := range strings.SplitSeq(diag, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || seen[line] {
			continue
		}

		if isDiagnoseSummaryLine(line) {
			causes = append(causes, line)
		} else if strings.HasPrefix(line, diagnoseErrorPrefix) {
			errs = append(errs, line)
		} else {
			continue
		}

		seen[line] = true
	}

	causes = append(causes, errs...)
	if len(causes) > maxDiagnoseSummaryLines {
		causes = causes[:maxDiagnoseSummaryLines]
	}

	summary := strings.Join(causes, "; ")
	if len(summary) > maxDiagnoseSummaryLen {
		summary = strings.ToValidUTF8(summary[:maxDiagnoseSummaryLen], "") + "..."
	}

	return summary
}

func isDiagnoseSummaryLine(line string) bool {
	for _, prefix := range diagnoseSummaryPrefixes {
		if strings.HasPrefix(line, prefix) {
			return true
		}
	}

	// VS and VSC lines are always present, only keep them when they carry an error
	if strings.HasPrefix(line, "VS ") || strings.HasPrefix(line, "VSC ") {
		_, errMessage, found := strings.Cut(line, ", errMessage ")
		if !found {
			return false
		}

		if strings.HasPrefix(line, "VSC ") {
			if i := strings.LastIndex(errMessage, ", handle "); i >= 0 {
				errMessage = errMessage[:i]
			} else {
				errMessage = strings.TrimSuffix(errMessage, ", handle")
			}
		}

		return strings.TrimSpace(errMessage) != ""
	}

	return false
}
